"""Pure evaluation contracts for the seed-11 SofT-GRPO/OPD study.

This module deliberately contains no CUDA, Ray, SGLang, W&B, or dataset
imports.  Generation uses the released SGLang engine in :mod:`generate_eval`;
the functions here make its persisted records and statistical estimands easy
to test on a CPU-only machine.
"""

from __future__ import annotations

import hashlib
import json
import math
from dataclasses import asdict, dataclass
from typing import Any, Dict, Iterable, Mapping, Sequence

import numpy as np


EVALUATION_SCHEMA_VERSION = 1
EVALUATION_PROTOCOL = "opd-softgrpo-seed11-evaluation-v1"
BOOTSTRAP_RESAMPLES = 10_000
BOOTSTRAP_SEED = 11

MODEL_LABELS = ("initial", "baseline", "opd")
BENCHMARKS = ("math500", "aime2024", "aime2025", "amc23", "gsm8k_test")
INFERENCE_MODES = ("native_soft", "hard_token")
MATH_VERIFY_BENCHMARKS = frozenset(BENCHMARKS)
GSM8K_GRADERS = (
    "math_verify",
    "released_last_boxed",
    "lm_eval_flexible_last_number",
)

# These are explicit rather than generated by a library RNG.  The same member
# at each sample index is used for every model and benchmark, making paired
# model comparisons reproducible across Python/NumPy releases.
COMMON_GENERATION_SEEDS = tuple(range(11, 43))
HARD_TOKEN_GENERATION_SEEDS = (COMMON_GENERATION_SEEDS[0],)

EXPECTED_EXAMPLE_COUNTS = {
    "math500": 500,
    "aime2024": 30,
    "aime2025": 30,
    "amc23": 40,
    "gsm8k_test": 1_319,
}


def graders_for_benchmark(benchmark: str) -> tuple[str, ...]:
    if benchmark not in BENCHMARKS:
        raise ValueError("unsupported benchmark: %r" % benchmark)
    if benchmark == "gsm8k_test":
        return GSM8K_GRADERS
    return ("math_verify",)


def stable_int63(*parts: Any) -> int:
    """Hash structured values to SGLang's nonnegative signed-int64 range."""

    encoded = json.dumps(parts, ensure_ascii=True, separators=(",", ":")).encode(
        "utf-8"
    )
    value = int.from_bytes(hashlib.sha256(encoded).digest()[:8], "big")
    return value & ((1 << 63) - 1)


def evaluation_request_seed(
    generation_seed: int, benchmark: str, example_id: str
) -> int:
    """Derive one request-local seed while preserving common random numbers."""

    if generation_seed not in COMMON_GENERATION_SEEDS:
        raise ValueError("generation seed is outside the locked seed set")
    if benchmark not in BENCHMARKS:
        raise ValueError("unsupported benchmark: %r" % benchmark)
    if not isinstance(example_id, str) or not example_id:
        raise ValueError("example_id must be non-empty")
    return stable_int63(
        EVALUATION_PROTOCOL,
        "request-seed",
        int(generation_seed),
        benchmark,
        example_id,
    )


def pass_at_k(n: int, correct: int, k: int) -> float:
    """Unbiased pass@k estimator from ``n`` samples and ``correct`` successes."""

    if not isinstance(n, int) or not isinstance(correct, int) or not isinstance(k, int):
        raise TypeError("n, correct, and k must be integers")
    if n <= 0 or not 0 <= correct <= n or not 1 <= k <= n:
        raise ValueError("require n > 0, 0 <= correct <= n, and 1 <= k <= n")
    if n - correct < k:
        return 1.0
    failure = 1.0
    for index in range(k):
        failure *= (n - correct - index) / (n - index)
    return 1.0 - failure


@dataclass(frozen=True)
class GenerationRecord:
    """One persisted completion from the exact released SGLang sampler."""

    model_label: str
    benchmark: str
    example_id: str
    inference_mode: str
    sample_index: int
    generation_seed: int
    request_seed: int
    response: str
    response_token_count: int
    finish_reason: str
    capped: bool
    latent_token_count: int
    hard_token_count: int
    close_tag: bool
    soft_to_hard: bool
    all_soft: bool
    mixture_entropy_mean: float | None
    top1_weight_mean: float | None
    soft_hard_agreement: float | None
    gold_answer: str
    schema_version: int = EVALUATION_SCHEMA_VERSION

    def __post_init__(self) -> None:
        if self.schema_version != EVALUATION_SCHEMA_VERSION:
            raise ValueError("unsupported generation-record schema")
        if self.model_label not in MODEL_LABELS:
            raise ValueError("unsupported model label: %r" % self.model_label)
        if self.benchmark not in BENCHMARKS:
            raise ValueError("unsupported benchmark: %r" % self.benchmark)
        if self.inference_mode not in INFERENCE_MODES:
            raise ValueError("unsupported inference mode: %r" % self.inference_mode)
        expected_seeds = (
            COMMON_GENERATION_SEEDS
            if self.inference_mode == "native_soft"
            else HARD_TOKEN_GENERATION_SEEDS
        )
        if type(self.sample_index) is not int or not 0 <= self.sample_index < len(
            expected_seeds
        ):
            raise ValueError("sample_index is outside the inference protocol")
        if (
            type(self.generation_seed) is not int
            or self.generation_seed != expected_seeds[self.sample_index]
        ):
            raise ValueError("generation_seed does not match sample_index")
        if type(self.request_seed) is not int or self.request_seed < 0:
            raise ValueError("request_seed must be a nonnegative integer")
        if self.request_seed != evaluation_request_seed(
            self.generation_seed, self.benchmark, self.example_id
        ):
            raise ValueError("request_seed does not match the locked derivation")
        if not isinstance(self.response, str):
            raise TypeError("response must be a string")
        if not isinstance(self.finish_reason, str) or not self.finish_reason:
            raise ValueError("finish_reason must be non-empty")
        if not isinstance(self.gold_answer, str) or not self.gold_answer.strip():
            raise ValueError("gold_answer must be non-empty")
        if type(self.response_token_count) is not int or self.response_token_count < 0:
            raise ValueError("response_token_count cannot be negative")
        if (
            type(self.latent_token_count) is not int
            or type(self.hard_token_count) is not int
            or self.latent_token_count < 0
            or self.hard_token_count < 0
        ):
            raise ValueError("latent/hard token counts cannot be negative")
        for name in ("capped", "close_tag", "soft_to_hard", "all_soft"):
            if type(getattr(self, name)) is not bool:
                raise TypeError("%s must be bool" % name)
        if self.latent_token_count + self.hard_token_count != self.response_token_count:
            raise ValueError("latent and hard counts must partition the response")
        if self.inference_mode == "hard_token":
            if self.latent_token_count != 0 or self.all_soft or self.soft_to_hard:
                raise ValueError("hard-token inference cannot contain soft-token state")
            if any(
                value is not None
                for value in (
                    self.mixture_entropy_mean,
                    self.top1_weight_mean,
                    self.soft_hard_agreement,
                )
            ):
                raise ValueError("hard-token inference has no mixture diagnostics")
        else:
            for name, value in (
                ("mixture_entropy_mean", self.mixture_entropy_mean),
                ("top1_weight_mean", self.top1_weight_mean),
                ("soft_hard_agreement", self.soft_hard_agreement),
            ):
                if self.latent_token_count and (
                    value is None or not math.isfinite(float(value))
                ):
                    raise ValueError("%s must be finite for a soft trajectory" % name)
            if self.latent_token_count == 0 and any(
                value is not None
                for value in (
                    self.mixture_entropy_mean,
                    self.top1_weight_mean,
                    self.soft_hard_agreement,
                )
            ):
                raise ValueError(
                    "a trajectory without latent tokens has no mixture diagnostics"
                )
            if self.soft_to_hard and not (
                self.latent_token_count > 0 and self.hard_token_count > 0
            ):
                raise ValueError("soft_to_hard requires both latent and hard tokens")
            if self.all_soft != (
                self.response_token_count > 0
                and self.latent_token_count == self.response_token_count
            ):
                raise ValueError("all_soft disagrees with the token partition")
            if self.mixture_entropy_mean is not None and self.mixture_entropy_mean < 0:
                raise ValueError("mixture entropy cannot be negative")
            for name in ("top1_weight_mean", "soft_hard_agreement"):
                value = getattr(self, name)
                if value is not None and not 0.0 <= float(value) <= 1.0:
                    raise ValueError("%s must be in [0, 1]" % name)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_mapping(cls, value: Mapping[str, Any]) -> "GenerationRecord":
        if not isinstance(value, Mapping):
            raise TypeError("generation record must be a mapping")
        expected = {field.name for field in cls.__dataclass_fields__.values()}
        unknown = set(value) - expected
        missing = expected - set(value)
        if unknown or missing:
            raise ValueError(
                "generation-record fields differ: missing=%s unknown=%s"
                % (sorted(missing), sorted(unknown))
            )
        return cls(**dict(value))


def correctness_by_example(
    rows: Iterable[Mapping[str, Any]],
    *,
    grader: str,
    expected_seeds: Sequence[int] = COMMON_GENERATION_SEEDS,
) -> Dict[str, tuple[int, ...]]:
    """Strictly group one grader's booleans in common-seed order."""

    expected = tuple(int(seed) for seed in expected_seeds)
    if len(expected) == 0 or len(set(expected)) != len(expected):
        raise ValueError("expected_seeds must be non-empty and unique")
    grouped: Dict[str, Dict[int, int]] = {}
    for row in rows:
        example_id = row.get("example_id")
        seed = row.get("generation_seed")
        scores = row.get("scores")
        if not isinstance(example_id, str) or not example_id:
            raise ValueError("scored row has invalid example_id")
        if not isinstance(seed, int):
            raise ValueError("scored row has invalid generation_seed")
        if not isinstance(scores, Mapping) or grader not in scores:
            raise ValueError("scored row is missing grader %r" % grader)
        score = scores[grader]
        if type(score) is not bool:
            raise TypeError("correctness scores must be bool")
        by_seed = grouped.setdefault(example_id, {})
        if seed in by_seed:
            raise ValueError("duplicate example/seed pair")
        by_seed[seed] = int(score)
    result = {}
    for example_id, by_seed in grouped.items():
        if set(by_seed) != set(expected):
            raise ValueError("example %s does not have the exact seed set" % example_id)
        result[example_id] = tuple(by_seed[seed] for seed in expected)
    if not result:
        raise ValueError("no scored examples")
    return result


def example_level_metric(
    outcomes: Mapping[str, Sequence[int]], metric: str
) -> Dict[str, float]:
    """Map exact per-seed outcomes to the example-level estimand."""

    if not outcomes:
        raise ValueError("outcomes cannot be empty")
    result: Dict[str, float] = {}
    for example_id, values in outcomes.items():
        vector = tuple(int(value) for value in values)
        if not vector or any(value not in (0, 1) for value in vector):
            raise ValueError("outcomes must be non-empty binary sequences")
        n = len(vector)
        correct = sum(vector)
        if metric in {"mean_at_32", "accuracy"}:
            result[example_id] = correct / n
        elif metric.startswith("pass_at_"):
            k = int(metric.rsplit("_", 1)[1])
            result[example_id] = pass_at_k(n, correct, k)
        else:
            raise ValueError("unknown evaluation metric: %r" % metric)
    return result


def paired_bootstrap_difference(
    treatment: Mapping[str, float],
    control: Mapping[str, float],
    *,
    resamples: int = BOOTSTRAP_RESAMPLES,
    seed: int = BOOTSTRAP_SEED,
    chunk_size: int = 256,
) -> Dict[str, float | int]:
    """Percentile CI for a paired example-level treatment-control difference."""

    if resamples != BOOTSTRAP_RESAMPLES:
        raise ValueError("the study contract requires exactly 10,000 resamples")
    if seed != BOOTSTRAP_SEED:
        raise ValueError("the study contract requires bootstrap seed 11")
    if chunk_size <= 0:
        raise ValueError("chunk_size must be positive")
    if set(treatment) != set(control) or not treatment:
        raise ValueError("paired bootstrap requires identical non-empty example IDs")
    ids = sorted(treatment)
    differences = np.asarray(
        [float(treatment[key]) - float(control[key]) for key in ids],
        dtype=np.float64,
    )
    if not np.isfinite(differences).all():
        raise ValueError("paired values must be finite")
    rng = np.random.default_rng(seed)
    bootstrap_means = np.empty(resamples, dtype=np.float64)
    for start in range(0, resamples, chunk_size):
        stop = min(resamples, start + chunk_size)
        indices = rng.integers(0, len(ids), size=(stop - start, len(ids)))
        bootstrap_means[start:stop] = differences[indices].mean(axis=1)
    low, high = np.quantile(bootstrap_means, [0.025, 0.975])
    return {
        "difference": float(differences.mean()),
        "ci_low": float(low),
        "ci_high": float(high),
        "confidence": 0.95,
        "resamples": resamples,
        "bootstrap_seed": seed,
        "example_count": len(ids),
    }


def validate_complete_matrix(
    records: Sequence[GenerationRecord],
    *,
    expected_models: Sequence[str] = MODEL_LABELS,
    expected_benchmarks: Sequence[str] = BENCHMARKS,
) -> None:
    """Reject incomplete, duplicated, or unpaired production evaluation rows."""

    keys = set()
    grouped: Dict[tuple[str, str, str], Dict[str, set[int]]] = {}
    gold_by_example: Dict[tuple[str, str], str] = {}
    for record in records:
        key = (
            record.model_label,
            record.benchmark,
            record.example_id,
            record.inference_mode,
            record.generation_seed,
        )
        if key in keys:
            raise ValueError("duplicate generation record: %r" % (key,))
        keys.add(key)
        group = grouped.setdefault(
            (record.model_label, record.benchmark, record.inference_mode), {}
        )
        group.setdefault(record.example_id, set()).add(record.generation_seed)
        gold_key = (record.benchmark, record.example_id)
        previous = gold_by_example.setdefault(gold_key, record.gold_answer)
        if previous != record.gold_answer:
            raise ValueError("gold answer changed across model evaluations")

    expected_group_keys = {
        (model, benchmark, mode)
        for model in expected_models
        for benchmark in expected_benchmarks
        for mode in INFERENCE_MODES
    }
    if set(grouped) != expected_group_keys:
        raise ValueError("evaluation group inventory is incomplete")

    for (model, benchmark, mode), examples in grouped.items():
        del model
        expected_count = EXPECTED_EXAMPLE_COUNTS[benchmark]
        if len(examples) != expected_count:
            raise ValueError(
                "%s/%s has %d examples, expected %d"
                % (benchmark, mode, len(examples), expected_count)
            )
        expected_seed_set = set(
            COMMON_GENERATION_SEEDS
            if mode == "native_soft"
            else HARD_TOKEN_GENERATION_SEEDS
        )
        if any(seeds != expected_seed_set for seeds in examples.values()):
            raise ValueError("%s/%s has an incomplete seed set" % (benchmark, mode))

    for benchmark in expected_benchmarks:
        reference = set(grouped[(expected_models[0], benchmark, "native_soft")])
        for model in expected_models[1:]:
            for mode in INFERENCE_MODES:
                if set(grouped[(model, benchmark, mode)]) != reference:
                    raise ValueError("model evaluations are not example-paired")
        if set(grouped[(expected_models[0], benchmark, "hard_token")]) != reference:
            raise ValueError("soft and hard evaluations are not example-paired")
